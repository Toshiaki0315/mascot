// npm test で実行する。くらにゃんぽいの口ぐせ（「にゃん」）の付け方
import assert from "node:assert/strict";
import { test } from "node:test";
import { hourLine, withHabit } from "./speech.ts";

// [いまの文, くらにゃんぽいのときの文]
const CASES: [string, string][] = [
  // おしゃべり
  ["えへへ", "えへへ"],
  ["うれしい！", "うれしいにゃん！"],
  ["もっとなでて〜", "もっとなでてにゃん〜"],
  ["くるりん！", "くるりんにゃん！"],
  ["めがまわる〜", "めがまわるにゃん〜"],
  ["ふぅ", "ふぅ"],
  ["なにしてるの？", "なにしてるのにゃん？"],
  ["いい天気だね", "いい天気だにゃん"],
  ["おなかすいたな", "おなかすいたにゃん"],
  ["びっくりした〜", "びっくりしたにゃん〜"],
  ["もう一回！", "もう一回にゃん！"],
  ["とうちゃく！", "とうちゃくにゃん！"],
  ["おはよう！", "おはようにゃん！"],
  ["ねてないよ…", "ねてないにゃん…"],
  ["そろそろ休憩しよう？", "そろそろ休憩しようにゃん？"],
  ["ちょっと伸びをしようよ", "ちょっと伸びをしようにゃん"],
  // メニューの操作などのひとこと
  ["5 分のタイマーを始めたよ", "5 分のタイマーを始めたにゃん"],
  ["ポモドーロをはじめるよ！", "ポモドーロをはじめるにゃん！"],
  ["クリップボードをメモに保存したよ", "クリップボードをメモに保存したにゃん"],
  ["コピーしたよ", "コピーしたにゃん"],
  ["コピーできなかった", "コピーできなかったにゃん"],
  ["場所を決めてね（リマインダー画面の「天気」）", "場所を決めてにゃん（リマインダー画面の「天気」）"],
  ["天気を取得できなかったよ", "天気を取得できなかったにゃん"],
  // ポモドーロ・タイマーの大きなふきだし
  ["作業おわり！ 5 分休憩しよう", "作業おわり！ 5 分休憩しようにゃん"],
  ["4 回おつかれさま！ 15 分ゆっくり休もう", "4 回おつかれさま！ 15 分ゆっくり休もうにゃん"],
  ["休憩おわり！ 次の作業（25 分）をはじめよう", "休憩おわり！ 次の作業（25 分）をはじめようにゃん"],
  [
    "席を外していたので、ポモドーロを止めたよ（作業 2 回おつかれさま）",
    "席を外していたので、ポモドーロを止めたにゃん（作業 2 回おつかれさま）",
  ],
  ["5 分のタイマーが終わりました", "5 分のタイマーが終わったにゃん"],
];

test("くらにゃんぽいのときは、一覧どおりに「にゃん」を付ける", () => {
  for (const [before, after] of CASES) {
    assert.equal(withHabit(before, "kuranyan"), after, before);
  }
});

test("ほかのキャラクターでは、そのまま", () => {
  for (const [before] of CASES) {
    for (const c of ["tora", "kuro", "shiro", "mike", "inu", "custom"] as const) {
      assert.equal(withHabit(before, c), before);
    }
  }
});

test("くらにゃんぽいの時報は「にゃん」", () => {
  assert.equal(hourLine(15, "kuranyan"), "15 時だにゃん");
  assert.equal(hourLine(15, "tora"), "15 時だにゃ");
});
